
# Strings we use to store text data in Python.
string_variable = "Hello, World!"
string_variable2 = 'This is also a string variable.'

# Integers we use to store whole numbers in Python.
integer_variable = 42

# Floats we use to store decimal numbers in Python.
float_variable = 3.14

# Booleans we use to store True or False values in Python
boolean_variable = True

print(f"String Variable 1: {string_variable}")
print(f"String Variable 2: {string_variable2}")
print(f"Integer Variable: {integer_variable}")
print(f"Float Variable: {float_variable}")
print(f"Boolean Variable: {boolean_variable}")